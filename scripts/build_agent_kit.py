def render_workbench_html(cfg: AgentKitConfig) -> str:
    """Render single-file offline Plus Guide style interactive HTML onboarding web app."""
    data = _build_workbench_data(cfg)
    raw_json = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    brand_mark = cfg.brand.split()[0].lower() if cfg.brand.split() else "store"
    replacements = {
        "__TITLE__": html.escape(f"{cfg.brand} · 新代理入营与出单交互指南"),
        "__BRAND__": html.escape(cfg.brand),
        "__BRAND_MARK__": html.escape(brand_mark),
        "__AGENT_FEE__": html.escape(cfg.agent_fee),
        "__AGENT_UPGRADE_URL__": html.escape(cfg.agent_upgrade_url),
        "__AGENT_UPGRADE_URL_ATTR__": html.escape(cfg.agent_upgrade_url, quote=True),
        "__OWNER_WECHAT__": html.escape(cfg.owner_wechat),
        "__DATA_JSON__": raw_json,
    }
    output = HTML_WORKBENCH_TEMPLATE
    for token, value in replacements.items():
        output = output.replace(token, value)
    return output


def build_agent_kit(
    cfg: AgentKitConfig,
    out_dir: Path | str = DEFAULT_OUT_DIR,
    zip_out: Path | str | None = DEFAULT_ZIP_OUT,
    web_out: Path | str | None = DEFAULT_WEB_OUT,
) -> dict[str, Path]:
    """Write sanitized docs, optional static web index.html, and optional shareable ZIP pack."""
    out_path = Path(out_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    html_content = render_workbench_html(cfg)
    doc_files: list[tuple[str, str]] = [
        (README_FILENAME, render_readme_txt(cfg)),
        (MANUAL_FILENAME, render_manual_markdown(cfg)),
        (COPYWRITING_FILENAME, render_copywriting_markdown(cfg)),
    ]

    outputs: dict[str, Path] = {}
    for fname, content in doc_files:
        target = out_path / fname
        target.write_text(content, encoding="utf-8")
        outputs[fname] = target

    if web_out is not None and str(web_out).strip():
        web_path = Path(web_out)
        web_path.parent.mkdir(parents=True, exist_ok=True)
        web_path.write_text(html_content, encoding="utf-8")
        outputs["web"] = web_path
    else:
        wb_target = out_path / WORKBENCH_FILENAME
        wb_target.write_text(html_content, encoding="utf-8")
        outputs[WORKBENCH_FILENAME] = wb_target

    if zip_out is not None and str(zip_out).strip():
        zip_path = Path(zip_out)
        zip_path.parent.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(
            zip_path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9
        ) as zf:
            for fname, content in doc_files:
                zf.writestr(f"{ZIP_ROOT_FOLDER}/{fname}", content.encode("utf-8"))
            zf.writestr(f"{ZIP_ROOT_FOLDER}/{WORKBENCH_FILENAME}", html_content.encode("utf-8"))
        outputs["zip"] = zip_path

    return outputs


def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build sanitized MyAIPlus agent onboarding docs, Plus Guide web app, and ZIP pack."
    )
    parser.add_argument("--brand", default="MyAIPlus 严选")
    parser.add_argument("--store-url", default="https://myaiplus.store")
    parser.add_argument("--agent-upgrade-url", default="https://myaiplus.store/user/group/index")
    parser.add_argument("--owner-wechat", default="xjmazh")
    parser.add_argument("--agent-fee", default="¥9.9")
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    parser.add_argument("--zip-out", type=Path, default=DEFAULT_ZIP_OUT)
    parser.add_argument("--web-out", type=Path, default=DEFAULT_WEB_OUT)
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    """CLI entrypoint to generate sanitized onboarding deliverables."""
    args = _parse_args(argv)
    cfg = AgentKitConfig(
        brand=args.brand,
        store_url=args.store_url,
        agent_upgrade_url=args.agent_upgrade_url,
        owner_wechat=args.owner_wechat,
        agent_fee=args.agent_fee,
    )
    outputs = build_agent_kit(
        cfg, out_dir=args.out_dir, zip_out=args.zip_out, web_out=args.web_out
    )
    for label, path in outputs.items():
        print(f"GENERATED [{label}]: {path} ({path.stat().st_size:,} bytes)")
    return 0


